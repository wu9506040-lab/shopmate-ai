"""共享词表：判断"这句话有没有实质业务诉求"。

为什么单独一个模块：这张表有两个消费者，而且**必须同时生效**——
  1. intent_service 的 chitchat 否决（"你好，尺码怎么选"不能判闲聊）
  2. guard 的 L2 灰区否决（余弦勉强过关时，有业务词就放行）
两处各写一份的结果是必然漂移：2026-11 就出过一次——L2 的领域词表里
有"发货"却没有"能发"，"新疆西藏能发吗几天到"被拦成领域外，
而它在知识库里是有答案的（运费/顺延条款）。所以收敛到一处。

注意：本表比 guard 的 DOMAIN_WORDS 更聚焦"诉求"，不含"你好/这款"这类
纯指代词——那些词解决的是"是不是在说我们这行"，不是"有没有要办的事"。
guard 侧两个表是并集关系，任一命中即放行。
"""
from __future__ import annotations

# 明确的业务诉求词。宁可多收，不要漏：漏一个词的代价是整类问题被误拦。
SUBSTANTIVE_KEYWORDS = frozenset([
    # 退换 / 售后
    "退款", "退货", "换货", "换码", "换尺码", "退钱", "申请", "退换",
    "补发", "换新", "瑕疵", "质量问题", "坏了", "破损", "开线",
    # 售后规则类（2026-11-17 补）：买家问的是"规则怎么算"，不是"我要退这单"。
    # 缺这几个词时，「七天无理由怎么算」「你们的三包政策」两处判为无诉求 →
    # guard L2 灰区否决把首轮提问整条拒掉（多轮反而能过，越熟越能问）。
    "无理由", "三包", "售后", "保修", "怎么算", "规则", "政策", "规定",
    # 订单 / 物流
    "订单", "物流", "快递", "发货", "能发", "发吗", "可发", "不发货",
    "签收", "到货", "下单", "单号", "运单", "偏远",
    "多久到", "几天到", "几天能", "什么时候发", "地址",
    # 价格 / 促销 / 票据
    "价格", "多少钱", "贵", "便宜", "少点", "砍价", "讲价", "议价",
    "优惠", "优惠券", "满减", "折扣", "促销", "活动",
    "包邮", "运费", "邮费", "发票", "开票", "专票", "保价", "差价",
    # 商品参数
    "库存", "货号", "款号", "规格", "颜色", "克重", "重量",
    "面料", "成分", "材质", "里料", "内胆", "羽绒", "羊毛", "羊绒", "真丝",
    "版型", "加绒", "克", "洗护", "干洗", "怎么洗", "能洗", "掉色", "缩水",
    "起球", "色差", "起静电",
    # 尺码
    "尺码", "腰围", "胸围", "臀围", "衣长", "肩宽", "袖长", "裤长",
    "大一码", "小一码", "什么码", "偏大", "偏小", "能穿", "穿多大", "几个",
])


def has_substantive_demand(text: str) -> bool:
    """句子里有没有明确的业务诉求（尺码/退换/物流/面料/价格…）。

    纯问候、纯感谢、"这个怎么样"这类模糊句不含表内任何词 → False。
    """
    return any(kw in text for kw in SUBSTANTIVE_KEYWORDS)
